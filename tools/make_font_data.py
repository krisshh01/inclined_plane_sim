#!/usr/bin/env python3
"""Regenerates font_data.h: small subsets of Inter Regular and SemiBold as C arrays.

Usage:  python3 tools/make_font_data.py [INTER_DIR]
        INTER_DIR holds Inter-Regular.otf and Inter-SemiBold.otf
        (default: /usr/share/fonts/opentype/inter, i.e. Debian/Ubuntu `fonts-inter`;
         or download the fonts from https://github.com/rsms/inter/releases).
Needs:  pip install fonttools

Inter is (c) The Inter Project Authors, licensed under the SIL Open Font License 1.1
(see LICENSE-Inter-OFL.txt).

The glyph set below must match the codepoints requested in fonts.c (Fonts_Load).
Vertical metrics are tightened so a requested size of N px really is an N px em
(raylib scales fonts so that ascent - descent == N, and Inter's native metrics are tall).
"""
import io
import os
import sys

from fontTools import subset
from fontTools.ttLib import TTFont

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "font_data.h")

# ASCII + degree, superscript two, middle dot, multiplication sign, theta, mu, true minus,
# less-or-equal, greater-or-equal, approximately-equal
UNICODES = list(range(0x20, 0x7F)) + [0xB0, 0xB2, 0xB7, 0xD7, 0x3B8, 0x3BC, 0x2212, 0x2264, 0x2265, 0x2248]


def build(path):
    opts = subset.Options()
    opts.layout_features = []        # raylib applies no kerning / substitutions
    opts.hinting = False
    opts.desubroutinize = True
    opts.notdef_outline = True
    opts.glyph_names = False
    opts.name_IDs = [0, 1, 2, 3, 4, 5, 6, 13, 14]   # keep copyright + license notices
    opts.name_legacy = True
    opts.name_languages = [0x409]

    font = TTFont(path)
    sub = subset.Subsetter(opts)
    sub.populate(unicodes=UNICODES)
    sub.subset(font)

    upm = font["head"].unitsPerEm
    asc, desc = round(0.80 * upm), -round(0.22 * upm)
    font["hhea"].ascent, font["hhea"].descent, font["hhea"].lineGap = asc, desc, 0
    os2 = font["OS/2"]
    os2.sTypoAscender, os2.sTypoDescender, os2.sTypoLineGap = asc, desc, 0
    os2.usWinAscent, os2.usWinDescent = asc, -desc

    buf = io.BytesIO()
    font.save(buf)
    return buf.getvalue()


def c_array(name, data):
    lines = ["static const unsigned char %s[] = {" % name]
    for i in range(0, len(data), 24):
        lines.append("    " + ", ".join("0x%02x" % b for b in data[i:i + 24]) + ",")
    lines.append("};")
    return "\n".join(lines)


def main():
    src = sys.argv[1] if len(sys.argv) > 1 else "/usr/share/fonts/opentype/inter"
    regular = build(os.path.join(src, "Inter-Regular.otf"))
    bold = build(os.path.join(src, "Inter-SemiBold.otf"))
    with open(OUT, "w") as f:
        f.write("/* Generated by tools/make_font_data.py - do not edit.\n"
                " * Subsets of Inter Regular / SemiBold (c) The Inter Project Authors,\n"
                " * SIL Open Font License 1.1 - see LICENSE-Inter-OFL.txt. */\n"
                "#ifndef FONT_DATA_H\n#define FONT_DATA_H\n\n")
        f.write(c_array("FONT_REGULAR_DATA", regular) + "\n\n")
        f.write(c_array("FONT_BOLD_DATA", bold) + "\n\n#endif\n")
    print("wrote %s (regular %d bytes, semibold %d bytes)" % (os.path.normpath(OUT), len(regular), len(bold)))


if __name__ == "__main__":
    main()
